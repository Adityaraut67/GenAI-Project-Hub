"""PDF audit report.

The deliverable a consumer or regulator could actually read: annotated
screenshot, findings with their provisions and explanations, and the honest
redesign. Carries the disclaimer on every copy — these are model outputs, not
legal determinations.
"""

from __future__ import annotations

import io
from datetime import datetime

from PIL import Image as PILImage
from reportlab.lib import colors
from reportlab.lib.enums import TA_LEFT
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import (
    Image as RLImage,
    PageBreak,
    Paragraph,
    SimpleDocTemplate,
    Spacer,
    Table,
    TableStyle,
)

from .overlay import SEVERITY_COLOUR, annotate

DISCLAIMER = (
    "This report is generated by an automated system and reflects model output, not a legal "
    "determination. Findings are indicative and require human review before being relied upon "
    "or acted on."
)

_styles = getSampleStyleSheet()
_H1 = ParagraphStyle("DPA_H1", parent=_styles["Heading1"], fontSize=18, spaceAfter=4)
_H2 = ParagraphStyle("DPA_H2", parent=_styles["Heading2"], fontSize=12, spaceBefore=10)
_BODY = ParagraphStyle("DPA_Body", parent=_styles["BodyText"], fontSize=9.5, leading=13)
_SMALL = ParagraphStyle(
    "DPA_Small", parent=_BODY, fontSize=8, textColor=colors.HexColor("#666666")
)
_CELL = ParagraphStyle("DPA_Cell", parent=_BODY, fontSize=8.5, leading=11, alignment=TA_LEFT)


def _fit_image(img: PILImage.Image, max_w: float, max_h: float) -> RLImage:
    buf = io.BytesIO()
    img.save(buf, format="PNG")
    buf.seek(0)
    ratio = min(max_w / img.width, max_h / img.height)
    return RLImage(buf, width=img.width * ratio, height=img.height * ratio)


def build_pdf(result, source_label: str = "uploaded screenshot") -> bytes:
    """Render an AuditResult to PDF bytes."""
    buf = io.BytesIO()
    doc = SimpleDocTemplate(
        buf,
        pagesize=A4,
        leftMargin=18 * mm,
        rightMargin=18 * mm,
        topMargin=16 * mm,
        bottomMargin=16 * mm,
        title="Dark Pattern Audit",
    )
    avail_w = doc.width
    story = []

    story.append(Paragraph("Dark Pattern Audit", _H1))
    story.append(
        Paragraph(
            "Assessed against the CCPA Guidelines for Prevention and Regulation of "
            "Dark Patterns, 2023 (India).",
            _SMALL,
        )
    )
    story.append(Spacer(1, 6))

    meta = result.meta or {}
    story.append(
        Paragraph(
            f"<b>Source:</b> {source_label}<br/>"
            f"<b>Generated:</b> {datetime.now().strftime('%d %B %Y, %H:%M')}<br/>"
            f"<b>Model:</b> {meta.get('model', 'n/a')} &nbsp; "
            f"<b>Prompt version:</b> {meta.get('prompt_version', 'n/a')} &nbsp; "
            f"<b>Verifier:</b> {'on' if meta.get('verifier') else 'off'}",
            _SMALL,
        )
    )
    story.append(Spacer(1, 10))

    findings = result.sorted_findings()

    if not findings:
        story.append(Paragraph("No dark patterns detected", _H2))
        story.append(
            Paragraph(
                "The detector found no prohibited patterns in this interface. Note that a "
                "clean result is evidence of compliance in the captured frame only; patterns "
                "such as subscription traps and drip pricing may appear later in a flow.",
                _BODY,
            )
        )
    else:
        high = sum(1 for f in findings if f.severity == "high")
        story.append(
            Paragraph(
                f"<b>{len(findings)} pattern(s) detected</b>"
                + (f", of which {high} high severity." if high else "."),
                _BODY,
            )
        )
        story.append(Spacer(1, 8))

    if result.image is not None:
        story.append(_fit_image(annotate(result.image, findings), avail_w, 150 * mm))
        story.append(Spacer(1, 4))
        story.append(Paragraph("Numbered regions correspond to the findings below.", _SMALL))

    # --- Findings table -----------------------------------------------------
    if findings:
        story.append(PageBreak())
        story.append(Paragraph("Findings", _H2))
        story.append(Spacer(1, 4))

        rows = [
            [
                Paragraph("<b>#</b>", _CELL),
                Paragraph("<b>Pattern</b>", _CELL),
                Paragraph("<b>Evidence</b>", _CELL),
                Paragraph("<b>Why it is manipulative</b>", _CELL),
                Paragraph("<b>Sev.</b>", _CELL),
            ]
        ]
        for i, f in enumerate(findings, start=1):
            rows.append(
                [
                    Paragraph(str(i), _CELL),
                    Paragraph(
                        f"{f.pattern.replace('_', ' ')}<br/>"
                        f"<font size=7 color='#666666'>{f.provision}</font>",
                        _CELL,
                    ),
                    Paragraph(f"&ldquo;{f.evidence}&rdquo;", _CELL),
                    Paragraph(
                        f.explanation
                        + (
                            f"<br/><font size=7 color='#666666'>DOM: {f.dom_corroboration}</font>"
                            if f.dom_corroboration
                            else ""
                        ),
                        _CELL,
                    ),
                    Paragraph(
                        f"{f.severity}<br/><font size=7>conf {f.confidence:.2f}</font>", _CELL
                    ),
                ]
            )

        widths = [8 * mm, 32 * mm, 45 * mm, 65 * mm, 17 * mm]
        table = Table(rows, colWidths=widths, repeatRows=1)
        style = [
            ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#DDDDDD")),
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#F2F2F2")),
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ("LEFTPADDING", (0, 0), (-1, -1), 4),
            ("RIGHTPADDING", (0, 0), (-1, -1), 4),
            ("TOPPADDING", (0, 0), (-1, -1), 4),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
        ]
        # Tint the severity cell so the table scans at a glance.
        for i, f in enumerate(findings, start=1):
            r, g, b = SEVERITY_COLOUR.get(f.severity, (120, 120, 120))
            style.append(
                ("BACKGROUND", (4, i), (4, i), colors.Color(r / 255, g / 255, b / 255, alpha=0.18))
            )
        table.setStyle(TableStyle(style))
        story.append(table)

    # --- Honest redesign ----------------------------------------------------
    rewritten = [f for f in findings if f.honest_rewrite]
    if rewritten:
        story.append(Spacer(1, 12))
        story.append(Paragraph("Honest redesign", _H2))
        for f in rewritten:
            hr = f.honest_rewrite
            layout = hr.get("layout_fix") or []
            story.append(
                Paragraph(
                    f"<b>{f.pattern.replace('_', ' ').title()}</b>", _BODY
                )
            )
            story.append(
                Table(
                    [
                        [
                            Paragraph("<b>Currently</b>", _CELL),
                            Paragraph(f"&ldquo;{hr.get('original_copy', f.evidence)}&rdquo;", _CELL),
                        ],
                        [
                            Paragraph("<b>Honest version</b>", _CELL),
                            Paragraph(f"&ldquo;{hr.get('honest_copy', '')}&rdquo;", _CELL),
                        ],
                        [
                            Paragraph("<b>Layout fix</b>", _CELL),
                            Paragraph(
                                "<br/>".join(f"&bull; {step}" for step in layout), _CELL
                            ),
                        ],
                        [
                            Paragraph("<b>Restores</b>", _CELL),
                            Paragraph(hr.get("principle", ""), _CELL),
                        ],
                    ],
                    colWidths=[32 * mm, avail_w - 32 * mm],
                    style=TableStyle(
                        [
                            ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#DDDDDD")),
                            ("VALIGN", (0, 0), (-1, -1), "TOP"),
                            ("TOPPADDING", (0, 0), (-1, -1), 4),
                            ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
                        ]
                    ),
                )
            )
            if hr.get("note"):
                story.append(Spacer(1, 3))
                story.append(Paragraph(hr["note"], _SMALL))
            story.append(Spacer(1, 8))

    # --- Dropped candidates and unmatched DOM signals -----------------------
    if result.dropped:
        story.append(Spacer(1, 10))
        story.append(Paragraph("Candidates rejected on review", _H2))
        story.append(
            Paragraph(
                "The verification pass examined and discarded these. Listed for transparency.",
                _SMALL,
            )
        )
        for f in result.dropped:
            story.append(
                Paragraph(
                    f"&bull; <b>{f.pattern.replace('_', ' ')}</b> &mdash; "
                    f"&ldquo;{f.evidence}&rdquo; &mdash; <i>{f.verifier_note}</i>",
                    _BODY,
                )
            )

    if result.missed_by_vision:
        story.append(Spacer(1, 10))
        story.append(Paragraph("Structural signals not seen in the image", _H2))
        for s in result.missed_by_vision:
            story.append(Paragraph(f"&bull; {s.pattern_hint}: {s.detail}", _BODY))

    story.append(Spacer(1, 14))
    story.append(Paragraph(DISCLAIMER, _SMALL))

    doc.build(story)
    return buf.getvalue()
